from pyspark.sql.functions import col


def transform_prediction_history(dataframe):
    """
    Transform the prediction history dataset.

    This dataset is currently empty and is intended to store
    predictions generated by ML models in later stages.
    """

    df = dataframe

    # ============================================================
    # STRING COLUMNS
    # ============================================================

    string_columns = [
        "prediction_id",
        "model",
        "prediction",
    ]

    for column_name in string_columns:
        if column_name in df.columns:
            df = df.withColumn(
                column_name,
                col(column_name).cast("string")
            )

    # ============================================================
    # CUSTOMER ID
    # ============================================================

    if "customer_id" in df.columns:
        df = df.withColumn(
            "customer_id",
            col("customer_id").cast("integer")
        )

    # ============================================================
    # PROBABILITY
    # ============================================================

    if "probability" in df.columns:
        df = df.withColumn(
            "probability",
            col("probability").cast("double")
        )

    # ============================================================
    # TIMESTAMP
    # ============================================================

    if "timestamp" in df.columns:
        df = df.withColumn(
            "timestamp",
            col("timestamp").cast("timestamp")
        )

    return df